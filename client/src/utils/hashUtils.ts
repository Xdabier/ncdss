/**
 * Simple deterministic hash (djb2) that produces a hex-like string.
 * Used to generate stable localStorage keys from intervention text.
 */
export function hashString(str: string): string {
  let hash = 5381;
  for (let i = 0; i < str.length; i++) {
    hash = ((hash << 5) + hash + str.charCodeAt(i)) >>> 0;
  }
  return hash.toString(16);
}
